#!/usr/bin/env node
// Builds public/assets/css/legacy.<hash>.css: the old theme stylesheets
// (Bootstrap, animate, swiper-bundle, sib-styles, styles) trimmed to the
// selectors the source still uses, concatenated in their original cascade
// order and minified. One render-blocking request of ~28 KB gzip instead of
// seven totalling ~89 KB (mobile LCP, 2026-11-23).
//
// Run from the site frontend root after changing classes that rely on the
// legacy CSS, then commit the new file and legacy-css.ts:
//   node scripts/build-legacy-css.mjs
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const order = ["bootstrap", "animate.min", "swiper-bundle.min", "sib-styles", "styles"];
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "legacy-css-"));
const npx = (...args) => execFileSync("npx", ["-y", ...args], { cwd: root, stdio: ["ignore", "inherit", "inherit"] });

// The purgecss CLI ignores regex safelists from a config file, so use its API
// from npx's cache (no package.json/bun.lock change for a rarely run script).
const bin = execFileSync("npx", ["-y", "-p", "purgecss@7.0.2", "-c", "command -v purgecss"], { cwd: root }).toString().trim();
const { PurgeCSS } = await import(path.join(path.dirname(fs.realpathSync(bin)), "../lib/purgecss.esm.js"));
const config = (await import(path.join(root, "scripts/legacy-css.purgecss.cjs"))).default;
const purged = await new PurgeCSS().purge({
  ...config,
  content: config.content.map((glob) => (glob.startsWith("!") ? "!" + path.join(root, glob.slice(1)) : path.join(root, glob))),
  css: config.css.map((file) => path.join(root, file)),
});
purged.forEach((result, i) => fs.writeFileSync(path.join(tmp, `${order[i]}.css`), result.css));
const combined = path.join(tmp, "combined.css");
fs.writeFileSync(combined, order.map((name) => fs.readFileSync(path.join(tmp, `${name}.css`), "utf8")).join("\n"));
const minified = path.join(tmp, "combined.min.css");
npx("lightningcss-cli@1.30.1", "--minify", combined, "-o", minified);

const css = fs.readFileSync(minified);
const name = `legacy.${createHash("sha256").update(css).digest("hex").slice(0, 10)}.css`;
const dir = path.join(root, "public/assets/css");
for (const old of fs.readdirSync(dir)) if (/^legacy\.[0-9a-f]{10}\.css$/.test(old)) fs.rmSync(path.join(dir, old));
fs.writeFileSync(path.join(dir, name), css);
fs.writeFileSync(
  path.join(root, "src/components/site/layout/legacy-css.ts"),
  `// Generated by scripts/build-legacy-css.mjs — do not edit.\nexport const LEGACY_CSS_HREF = "/assets/css/${name}";\n`,
);
fs.rmSync(tmp, { recursive: true });
console.log(`wrote public/assets/css/${name} (${css.length} bytes)`);
